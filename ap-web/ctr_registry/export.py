"""Registry repository file layout, written to a local directory.

The registry repository is the record apworld builds pin. This module builds
its files from the database and writes them to a directory; it does not touch
git or GitHub (the public repository does not exist yet, and the web tier
never holds write credentials). A later Atlas step will commit the directory
to the repository as an export pull request.

Layout (all JSON is canonical: sorted keys, two-space indent, trailing newline):

    README.md             what the repository is and is not
    registry.json         every recorded track, revisions without descriptors
    tracks/<key>.json     one file per track, with full revisions and descriptors
    named_tracks.json     the apworld build input (format 1), named blocks only
    tools/check_registry.py   stdlib-only schema, identity and freeze checker
    DIGEST.json           sha256 over registry.json and tracks/*, plus time

Only names, credits, hashes, descriptors and locator links appear. No track
file, no submitter identity, no reviewer name.

The digest covers registry.json and tracks/*.json. named_tracks.json embeds it,
so a build can pin one commit and one digest.
"""

from __future__ import annotations

import hashlib
import json
import os
from datetime import datetime, timezone
from pathlib import Path
from typing import Iterable, Optional

from ctr_registry import rules

DIGEST_FILE = "DIGEST.json"
PUBLIC_REVISION_FIELDS = ("revision", "content_id", "hash_state", "files", "modes", "evidence",
                          "descriptor_schema", "apworld_min", "apworld_max")

README = """# CTR custom-track registry

Reviewed names, credits, hashes and links for CTR Archipelago custom tracks.
It holds no track files: downloads stay on the creators' pages and Project
Saphi.

- `registry.json` lists every recorded track and its revisions.
- `tracks/<key>.json` holds one track with the full descriptor of each revision.
- `named_tracks.json` is the input an apworld build pins. It lists tracks that
  have a named id block, in block order.
- `tools/check_registry.py` runs the schema, identity and freeze checks. Run it
  with `--previous <older checkout>` to compare against the last published set.

Identity is frozen: `track_key`, `block_index`, a shipped `ap_name` and
revision hashes never change. Titles, credits and links can be corrected.
Files in this repository are generated by AP-Pie's export job and reviewed
there; change them through that job, not by hand.
"""


def canonical(doc) -> bytes:
    return (json.dumps(doc, sort_keys=True, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def _date(value) -> Optional[str]:
    return value.date().isoformat() if hasattr(value, "date") else (value or None)


def _revision_doc(rev: dict, with_descriptor: bool) -> dict:
    out = {k: rev.get(k) for k in PUBLIC_REVISION_FIELDS}
    out["files"] = rev.get("files") or {}
    out["modes"] = rev.get("modes") or []
    out["evidence"] = rev.get("evidence") or {}
    saphi = (rev.get("provenance") or {}).get("saphi_downloads")
    if saphi:
        out["provenance"] = {"saphi_downloads": saphi}
    if with_descriptor:
        out["descriptor"] = rev.get("descriptor")
    return out


def entry_doc(entry: dict, revisions: list[dict], keys_by_id: dict, with_descriptor: bool) -> dict:
    prov = entry.get("provenance") or {}
    saphi = prov.get("saphi") or {}
    provenance = {}
    if saphi:
        provenance["saphi"] = {k: saphi.get(k) for k in ("track_id", "category", "url")}
    return {
        "track_key": entry["track_key"],
        "state": entry["state"],
        "display_title": entry["display_title"],
        "credits": entry.get("credits") or [],
        "links": entry.get("links") or {},
        "provenance": provenance,
        "block_index": entry.get("block_index"),
        "ap_name": entry.get("ap_name"),
        "shipped_in": entry.get("shipped_in"),
        "review": {
            "reviewed_at": _date(entry.get("reviewed_at")),
            "superseded_by": keys_by_id.get(entry.get("superseded_by")),
        },
        "revisions": [_revision_doc(r, with_descriptor) for r in revisions],
    }


def _sort_key(entry: dict):
    return (entry["block_index"] is None, entry["block_index"] or 0, entry["track_key"])


def build_files(records: Iterable[tuple[dict, list[dict]]],
                states: Iterable[str] = rules.RECORD_STATES) -> tuple[dict[str, bytes], str]:
    """Return ({relative path: bytes}, digest) for the data files.

    `records` is store.record_entries(). Entries without a track_key are
    skipped: a candidate has no identity yet."""
    states = set(states)
    rows = [(e, r) for e, r in records if e["track_key"] and e["state"] in states]
    rows.sort(key=lambda er: _sort_key(er[0]))
    keys_by_id = {e["id"]: e["track_key"] for e, _ in rows}
    files: dict[str, bytes] = {}
    summaries = []
    for entry, revs in rows:
        files[f"tracks/{entry['track_key']}.json"] = canonical(entry_doc(entry, revs, keys_by_id, True))
        summaries.append(entry_doc(entry, revs, keys_by_id, False))
    files["registry.json"] = canonical({
        "schema_version": rules.SCHEMA_VERSION,
        "id_scheme": rules.id_ranges(),
        "tracks": summaries,
    })
    digest = digest_of(files)
    named = [
        {"track_key": e["track_key"], "block_index": e["block_index"], "ap_name": e["ap_name"],
         "shipped_in": e["shipped_in"],
         "revisions": [r["content_id"] for r in revs if r.get("content_id")]}
        for e, revs in rows if e["block_index"] is not None
    ]
    files["named_tracks.json"] = canonical({
        "format": 1,
        "registry": {"repository": None, "commit": None, "digest": digest},
        "tracks": named,
    })
    return files, digest


def digest_of(files: dict[str, bytes]) -> str:
    h = hashlib.sha256()
    for path in sorted(p for p in files if p == "registry.json" or p.startswith("tracks/")):
        h.update(path.encode() + b"\0" + hashlib.sha256(files[path]).hexdigest().encode() + b"\n")
    return h.hexdigest()


def _checker_source() -> bytes:
    return (Path(__file__).with_name("check.py")).read_bytes()


def write_export(records, out_dir: str, now: Optional[datetime] = None) -> dict:
    """Write the registry files to `out_dir` and return a summary.

    Files are replaced one at a time (temp file, then rename) and stale
    tracks/*.json are removed; DIGEST.json is written last, so a reader that
    sees a DIGEST.json matching the data sees a complete set. An existing
    `.git` directory in `out_dir` is left alone. Nothing is deleted outside
    tracks/."""
    files, digest = build_files(records)
    files["README.md"] = README.encode("utf-8")
    files["tools/check_registry.py"] = _checker_source()
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "tracks").mkdir(exist_ok=True)
    (out / "tools").mkdir(exist_ok=True)

    changed = 0
    for rel, data in sorted(files.items()):
        target = out / rel
        if target.exists() and target.read_bytes() == data:
            continue
        tmp = target.with_name(target.name + ".tmp")
        tmp.write_bytes(data)
        os.replace(tmp, target)
        changed += 1
    wanted = {rel.split("/", 1)[1] for rel in files if rel.startswith("tracks/")}
    removed = 0
    for stale in (out / "tracks").glob("*.json"):
        if stale.name not in wanted:
            stale.unlink()
            removed += 1

    digest_path = out / DIGEST_FILE
    generated_at = (now or datetime.now(timezone.utc)).replace(microsecond=0).isoformat()
    if digest_path.exists():
        try:
            previous = json.loads(digest_path.read_text("utf-8"))
            if previous.get("digest") == digest:
                generated_at = previous.get("generated_at", generated_at)
        except (ValueError, OSError):
            pass
    doc = canonical({"schema_version": rules.SCHEMA_VERSION, "digest": digest,
                     "generated_at": generated_at,
                     "tracks": sum(1 for p in files if p.startswith("tracks/"))})
    if not digest_path.exists() or digest_path.read_bytes() != doc:
        tmp = digest_path.with_name(DIGEST_FILE + ".tmp")
        tmp.write_bytes(doc)
        os.replace(tmp, digest_path)
        changed += 1
    return {"out_dir": str(out), "digest": digest, "files": len(files) + 1,
            "changed": changed, "removed": removed,
            "tracks": sum(1 for p in files if p.startswith("tracks/"))}


def public_publication(records) -> dict:
    """The document GET /api/ctr/tracks/publication serves: approved and named
    tracks only, with the digest of that public view."""
    files, digest = build_files(records, rules.PUBLIC_STATES)
    doc = json.loads(files["registry.json"])
    doc["digest"] = digest
    return doc
